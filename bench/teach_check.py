def mean(xs):
    xs = [x for x in xs if x is not None]
    return sum(xs) / len(xs) if xs else None


def ranks(xs):
    order = sorted(range(len(xs)), key=lambda i: xs[i])
    r = [0.0] * len(xs)
    i = 0
    while i < len(order):
        j = i
        while j + 1 < len(order) and xs[order[j + 1]] == xs[order[i]]:
            j += 1
        for k in range(i, j + 1):
            r[order[k]] = (i + j) / 2 + 1
        i = j + 1
    return r


def pearson(a, b):
    ma, mb = sum(a) / len(a), sum(b) / len(b)
    va, vb = sum((x - ma) ** 2 for x in a), sum((y - mb) ** 2 for y in b)
    return None if not va or not vb else sum((x - ma) * (y - mb) for x, y in zip(a, b)) / (va * vb) ** 0.5


def spearman(pairs, shuffles=10000, seed=0):
    """Rank correlation with a two-sided permutation p (pairs with a missing value are left out)."""
    pairs = [(a, b) for a, b in pairs if a is not None and b is not None]
    if len(pairs) < 4:
        return {"n": len(pairs), "rho": None, "p": None}
    ra, rb = ranks([a for a, _ in pairs]), ranks([b for _, b in pairs])
    rho = pearson(ra, rb)
    if rho is None:
        return {"n": len(pairs), "rho": None, "p": None}
    rng, hits = random.Random(seed), 0
    for _ in range(shuffles):
        rng.shuffle(rb)
        hits += abs(pearson(ra, rb)) >= abs(rho) - 1e-12
    return {"n": len(pairs), "rho": round(rho, 3), "p": round((hits + 1) / (shuffles + 1), 4)}


def sign(diffs, eps=1e-9):
    """Mean difference, wins/ties/losses and the exact two-sided sign-test p."""
    from math import comb

    diffs = [d for d in diffs if d is not None]
    w, l = sum(d > eps for d in diffs), sum(d < -eps for d in diffs)
    n = w + l
    p = min(1.0, 2 * sum(comb(n, k) for k in range(0, min(w, l) + 1)) / 2**n) if n else 1.0
    return {"n": len(diffs), "mean": None if not diffs else round(sum(diffs) / len(diffs), 4), "wins": w,
            "ties": len(diffs) - n, "losses": l, "p": round(p, 4)}  # fmt: skip


def centred(rows, key):
    """Each video's value minus its concept's mean over the sets (takes the concept's difficulty out)."""
    by = {}
    for r in rows:
        if key(r) is not None:
            by.setdefault(r["slug"], []).append(key(r))
    return [None if key(r) is None else key(r) - sum(by[r["slug"]]) / len(by[r["slug"]]) for r in rows]


def covered_gain(rows, shuffles=10000, seed=0):
    """TEST questions the judge finds covered against the others: the student's gain in P(right) from the frames.
    The permutation shuffles the judge's labels inside each video."""
    groups = []
    for r in rows:
        g = [(it["shown"], it["p_frames"] - it["p_blind"]) for it in r["coverage"]["items"] if "p_frames" in it]
        if g:
            groups.append(g)
    flat = [x for g in groups for x in g]
    yes, no = [d for s, d in flat if s], [d for s, d in flat if not s]
    if not yes or not no:
        return {"covered": len(yes), "not_covered": len(no), "diff": None, "p": None,
                "gain_covered": mean(yes), "gain_not_covered": mean(no)}  # fmt: skip
    diff = mean(yes) - mean(no)
    rng, hits = random.Random(seed), 0
    for _ in range(shuffles):
        y, n = [], []
        for g in groups:
            labels = [s for s, _ in g]
            rng.shuffle(labels)
            for s, (_, d) in zip(labels, g):
                (y if s else n).append(d)
        if y and n:
            hits += abs(mean(y) - mean(n)) >= abs(diff) - 1e-12
    return {"covered": len(yes), "not_covered": len(no), "gain_covered": round(mean(yes), 4),
            "gain_not_covered": round(mean(no), 4), "diff": round(diff, 4), "p": round((hits + 1) / (shuffles + 1), 4)}  # fmt: skip


def analyse(rows):
    dl, cv = (lambda r: r["delivery"]["delivery"]), (lambda r: r["coverage"]["coverage"])
    novel = [r for r in rows if r["set"] in NOVEL_SETS]
    rep = {"sets": {}, "controls": {}, "relation": {}}
    for s in (*NOVEL_SETS, "mmmc"):
        rs = [r for r in rows if r["set"] == s]
        if not rs:
            continue
        rep["sets"][s] = {"label": LABEL[s], "videos": len(rs), "delivery": mean(map(dl, rs)), "coverage": mean(map(cv, rs)),
                          "m9": mean(r["m9"] for r in rs), "mvqs": mean(r["mvqs"] for r in rs),
                          "delivery_defined": sum(dl(r) is not None for r in rs),
                          "questions": mean(r["delivery"]["questions"] for r in rs),
                          "written": mean(r["delivery"]["written"] for r in rs),
                          "blind": mean(r["delivery"].get("blind") for r in rs),
                          "own": mean(r["delivery"].get("own") for r in rs)}  # fmt: skip
    for s in ("local", "mmmc"):
        rs = [r for r in rows if r["set"] == s]
        if not rs:
            continue
        rep["controls"][s] = {
            "delivery_own": mean(map(dl, rs)), "delivery_other": mean(r["delivery"]["control"] for r in rs),
            "delivery_own_minus_other": sign([None if dl(r) is None or r["delivery"]["control"] is None
                                              else dl(r) - r["delivery"]["control"] for r in rs]),
            "coverage_own": mean(map(cv, rs)), "coverage_other": mean(r["coverage"]["control"] for r in rs),
            "coverage_own_minus_other": sign([None if r["coverage"]["control"] is None else cv(r) - r["coverage"]["control"]
                                              for r in rs])}  # fmt: skip
    m9 = [r["m9"] for r in novel]
    rep["relation"] = {
        "delivery_vs_m9_all": spearman(zip(map(dl, novel), m9)),
        "coverage_vs_m9_all": spearman(zip(map(cv, novel), m9)),
        "mvqs_vs_m9_all": spearman(zip([r["mvqs"] for r in novel], m9)),
        "delivery_vs_m9_within_concept": spearman(zip(centred(novel, dl), centred(novel, lambda r: r["m9"]))),
        "coverage_vs_m9_within_concept": spearman(zip(centred(novel, cv), centred(novel, lambda r: r["m9"]))),
        "mvqs_vs_m9_within_concept": spearman(zip(centred(novel, lambda r: r["mvqs"]), centred(novel, lambda r: r["m9"]))),
        "delivery_vs_m9_local": spearman([(dl(r), r["m9"]) for r in novel if r["set"] == "local"]),
        "coverage_vs_m9_local": spearman([(cv(r), r["m9"]) for r in novel if r["set"] == "local"]),
        "delivery_vs_coverage_all": spearman(zip(map(dl, novel), map(cv, novel))),
    }  # fmt: skip
    rep["covered_gain"] = covered_gain(novel)
    rep["covered_gain_by_set"] = {s: covered_gain([r for r in novel if r["set"] == s]) for s in NOVEL_SETS}
    # the same questions on the local video and on its Claude-fixed layout (only questions asked of both)
    by = {(r["set"], r["slug"]): r for r in rows}
    pairs = []
    for (s, slug), r in by.items():
        if s != "claude_layout" or ("local", slug) not in by:
            continue
        a = {it["id"]: it for it in by[("local", slug)]["delivery"]["items"]}
        b = {it["id"]: it for it in r["delivery"]["items"]}
        ids = sorted(set(a) & set(b))
        if not ids:
            continue
        own_a, own_b = {i: a[i]["p_own"] for i in ids}, {i: b[i]["p_own"] for i in ids}
        blind = {i: a[i]["p_blind"] for i in ids}
        pairs.append({"slug": slug, "questions": len(ids), "local": delivery.nvg_of(own_a, blind),
                      "claude_layout": delivery.nvg_of(own_b, blind), "m9_local": by[("local", slug)]["m9"],
                      "m9_claude_layout": r["m9"], "mvqs_local": by[("local", slug)]["mvqs"], "mvqs_claude_layout": r["mvqs"]})  # fmt: skip
    rep["layout_pairs"] = {"pairs": pairs,
                           "delivery": sign([None if p["local"] is None or p["claude_layout"] is None
                                             else p["claude_layout"] - p["local"] for p in pairs]),
                           "m9": sign([p["m9_claude_layout"] - p["m9_local"] for p in pairs]),
                           "mvqs": sign([p["mvqs_claude_layout"] - p["mvqs_local"] for p in pairs])}  # fmt: skip
    bp = []
    for (s, slug), r in by.items():
        if s == "blueprint" and ("qwen", slug) in by:
            q = by[("qwen", slug)]
            bp.append({"slug": slug, "delivery_blueprint": dl(r), "delivery_plain": dl(q), "coverage_blueprint": cv(r),
                       "coverage_plain": cv(q), "m9_blueprint": r["m9"], "m9_plain": q["m9"]})  # fmt: skip
    diff = lambda k: sign([None if p[f"{k}_blueprint"] is None or p[f"{k}_plain"] is None
                           else p[f"{k}_blueprint"] - p[f"{k}_plain"] for p in bp])  # fmt: skip
    rep["blueprint_pairs"] = {"pairs": bp, "delivery": diff("delivery"), "coverage": diff("coverage"), "m9": diff("m9")}
    return rep


def pct(x, signed=False):
    return "--" if x is None else f"{100 * x:+.1f}" if signed else f"{100 * x:.1f}"


def markdown(rows, rep):
    out = ["# Teach check: delivery and coverage", "",
           "Delivery: can the student read what this video shows (questions about the video's own content)? "
           "Coverage: does the video show what each final-quiz question needs (a judge that may know the topic)? "
           "Both on 3 frames per section, 0-100. See c2vlab/delivery.py.", "",
           "| Set | Videos | Delivery | Coverage | M9 | Layout score | Delivery questions kept (of written) |",
           "|---|---|---|---|---|---|---|"]  # fmt: skip
    for s, r in rep["sets"].items():
        out.append(f"| {r['label']} | {r['videos']} | {pct(r['delivery'])} | {pct(r['coverage'])} | {pct(r['m9'])} | "
                   f"{'--' if r['mvqs'] is None else round(r['mvqs'], 1)} | {r['questions']:.1f} ({r['written']:.1f}) |")  # fmt: skip
    out += ["", "## Controls: the same questions on another topic's video", "",
            "| Set | Delivery own | Delivery other | own > other | Coverage own | Coverage other | own > other |",
            "|---|---|---|---|---|---|---|"]  # fmt: skip
    for s, c in rep["controls"].items():
        a, b = c["delivery_own_minus_other"], c["coverage_own_minus_other"]
        out.append(f"| {LABEL[s]} | {pct(c['delivery_own'])} | {pct(c['delivery_other'])} | {a['wins']}/{a['n']} (p {a['p']}) | "
                   f"{pct(c['coverage_own'])} | {pct(c['coverage_other'])} | {b['wins']}/{b['n']} (p {b['p']}) |")  # fmt: skip
    out += ["", "## Do they move with M9? (NOVEL-12 videos; Spearman, permutation p)", "", "| Pair | n | rho | p |", "|---|---|---|---|"]
    for k, v in rep["relation"].items():
        out.append(f"| {k.replace('_', ' ')} | {v['n']} | {v['rho']} | {v['p']} |")
    g = rep["covered_gain"]
    out += ["", "## Coverage, question by question", "",
            f"Covered questions ({g['covered']}): the frames raise P(right) by {pct(g['gain_covered'], True)} points. "
            f"Not covered ({g['not_covered']}): {pct(g['gain_not_covered'], True)}. Difference {pct(g['diff'], True)} "
            f"(labels shuffled inside each video: p {g['p']}).", ""]  # fmt: skip
    lp = rep["layout_pairs"]
    out += ["## Layout fix (same text): Claude-fixed minus local", "",
            f"Delivery {pct(lp['delivery']['mean'], True)} ({lp['delivery']['wins']}/{lp['delivery']['ties']}/{lp['delivery']['losses']}, "
            f"p {lp['delivery']['p']}); M9 {pct(lp['m9']['mean'], True)} ({lp['m9']['wins']}/{lp['m9']['ties']}/{lp['m9']['losses']}); "
            f"layout score {lp['mvqs']['mean']:+.1f}.", "",
            "## Blueprint prompt minus plain prompt (same plans, local coder)", "",
            *(f"- {k}: {pct(v['mean'], True)} ({v['wins']}/{v['ties']}/{v['losses']}, sign-test p {v['p']})"
              for k, v in rep["blueprint_pairs"].items() if k != "pairs"), "",
            "## Every video", "", "| Set | Topic | Sections | Delivery | on other | Questions | Coverage | on other | M9 |",
            "|---|---|---|---|---|---|---|---|---|"]  # fmt: skip
    for r in rows:
        d, c = r["delivery"], r["coverage"]
        out.append(f"| {r['set']} | {r['topic'][:44]} | {r['sections']}/{r['planned']} | {pct(d['delivery'])} | {pct(d['control'])} | "
                   f"{d['questions']} | {pct(c['coverage'])} | {pct(c['control'])} | {pct(r['m9'])} |")  # fmt: skip
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--analyse-only", action="store_true")
    ap.add_argument("--sets", default="", help="comma list of sets to measure (default: all)")
    args = ap.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    path = OUT / "rows.json"
    rows = json.loads(path.read_text()) if path.exists() else []
    if not args.analyse_only:
        have = {(r["set"], r["slug"]): r for r in rows}
        want = [v for v in videos() if not args.sets or v["set"] in args.sets.split(",")]
        for v in want:
            try:
                have[(v["set"], v["slug"])] = measure(v)
            except Exception as exc:  # noqa: BLE001 - one video must not stop the study; it is reported as missing
                print(f"[teach-check] {v['set']}/{v['slug']}: FAILED {type(exc).__name__}: {exc}", flush=True)
            order = [(v["set"], v["slug"]) for v in videos()]
            rows = [have[k] for k in order if k in have]
            path.write_text(json.dumps(rows, indent=1, ensure_ascii=False))
    rep = analyse(rows)
    (OUT / "report.json").write_text(json.dumps(rep, indent=1, ensure_ascii=False))
    (OUT / "report.md").write_text(markdown(rows, rep))
    print(markdown(rows, rep))


if __name__ == "__main__":
    main()
