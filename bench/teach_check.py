"""Delivery and coverage (c2vlab/delivery.py) on videos where M9 says how much each one teaches (NOVEL-12), and on real
MMMC lessons, where M9 is undefined because the student already knows the answers.

    python bench/teach_check.py                  -> bench/results/teach-check/{rows.json, report.json, report.md}
    python bench/teach_check.py --analyse-only   (from the cached answers)

Sets of videos:
  local          NOVEL-12 base videos of the local models (10 admitted concepts); control: the next concept's video
  claude_layout  the same videos with layout fixed by Claude (text unchanged): asked the local video's delivery quiz
  sonnet, opus   the whole video generated by that Claude model (generator study)
  qwen, blueprint  the local models in the best configuration, with the plain and with the blueprint coder prompt on
                 the same plans (bench/blueprint_study.py)
  mmmc           the 12 pilot topics of MMMC, base videos (real lessons); control: the next topic's video

One process, one call at a time: calls on the same frames follow each other so the server reuses the frames it read.
Every answer is cached under bench/results/teach-check/cache/<set>/<slug>/; nothing is written into runs/.
"""

