LABEL = {"local": "Local models, base", "claude_layout": "Local + Claude layout fix",
         "qwen": "Local models, plain prompt (best configuration)", "blueprint": "Local models, blueprint prompt",
         "sonnet": "Claude Sonnet 5.5", "opus": "Claude Opus 5.5", "mmmc": "Real lessons (MMMC), local models"}  # fmt: skip


def videos():
    """Every video of the study: set, slug, folders, and M9 where it is defined."""
    layout = {generate.slug(r["topic"]): r for r in json.loads((ROOT / "bench/results/layout-study/rows.json").read_text())}
    novel = [s for s, r in layout.items() if "claude" in r and (RUNS / s / "claude_fixed" / "video.mp4").exists()]
    out = []
    for i, s in enumerate(novel):
        nxt = RUNS / novel[(i + 1) % len(novel)]
        out.append({"set": "local", "slug": s, "dir": RUNS / s, "topic_dir": RUNS / s, "other": nxt,
                    "m9": layout[s]["ours"]["teaching"]["M9"], "mvqs": layout[s]["ours"]["layout"]["mvqs_mean"],
                    "conflicts": layout[s]["ours"]["layout"]["conflicts"]})  # fmt: skip
        out.append({"set": "claude_layout", "slug": s, "dir": RUNS / s / "claude_fixed", "topic_dir": RUNS / s,
                    "other": None, "quiz_from": ("local", s), "m9": layout[s]["claude"]["teaching"]["M9"],
                    "mvqs": layout[s]["claude"]["layout"]["mvqs_mean"],
                    "conflicts": layout[s]["claude"]["layout"]["conflicts"]})  # fmt: skip
    for fam in ("sonnet", "opus"):
        rows = json.loads((ROOT / f"bench/results/claude-gen/rows_{fam}.json").read_text())
        for r in rows:
            d = RUNS / "claude-gen" / fam / r["slug"]
            if r["slug"] in novel and (d / "video.mp4").exists() and (r.get("teaching") or {}).get("base"):
                out.append({"set": fam, "slug": r["slug"], "dir": d, "topic_dir": d, "other": None,
                            "m9": r["teaching"]["base"]["m9"], "mvqs": r["layout"]["mvqs_mean"],
                            "conflicts": r["layout"]["conflicts"]})  # fmt: skip
    # the blueprint study (bench/blueprint_study.py): the same plans coded with the plain and with the blueprint prompt
    bp = ROOT / "bench/results/blueprint/rows.json"
    plain = {r["slug"]: r for r in json.loads((ROOT / "bench/results/claude-gen/rows_qwen.json").read_text())}
    for r in json.loads(bp.read_text()) if bp.exists() else []:
        d, q = RUNS / "blueprint" / "qwen-blueprint" / r.get("slug", ""), plain.get(r.get("slug"))
        if "teaching" not in r or not q or r["slug"] not in novel or not (d / "video.mp4").exists():
            continue
        qd = RUNS / "claude-gen" / "qwen" / r["slug"]
        out.append({"set": "qwen", "slug": r["slug"], "dir": qd, "topic_dir": qd, "other": None,
                    "m9": q["teaching"]["base"]["m9"], "mvqs": r["ref"]["layout"]["mvqs_mean"],
                    "conflicts": r["ref"]["layout"]["conflicts"]})  # fmt: skip
        out.append({"set": "blueprint", "slug": r["slug"], "dir": d, "topic_dir": d, "other": None,
                    "m9": r["teaching"]["base"]["m9"], "mvqs": r["layout"]["mvqs_mean"],
                    "conflicts": r["layout"]["conflicts"]})  # fmt: skip
    pilot = [generate.slug(t) for t in json.loads((ROOT / "bench/results/mmmc-n12-seed0/topics.json").read_text())]
    pilot = [s for s in pilot if (RUNS / s / "video.mp4").exists()]
    for i, s in enumerate(pilot):
        out.append({"set": "mmmc", "slug": s, "dir": RUNS / s, "topic_dir": RUNS / s,
                    "other": RUNS / pilot[(i + 1) % len(pilot)], "m9": None, "mvqs": None, "conflicts": None})  # fmt: skip
    return out


def test_gains(v):
    """TEST question id -> P(right) with the frames minus with no material (the answers M9 is computed from)."""
    fr, bl = v["dir"] / "dv_frames_test.json", v["topic_dir"] / "dv_blind_test.json"
    if not (fr.exists() and bl.exists()):
        return {}
    a, b = delivery.items(json.loads(fr.read_text())), delivery.items(json.loads(bl.read_text()))
    return {i: {"p_frames": round(a[i], 4), "p_blind": round(b[i], 4)} for i in a if i in b}


def measure(v, log=print):
    plan = json.loads((v["topic_dir"] / "plan.json").read_text())
    store = CACHE / v["set"] / v["slug"]
    qf = v.get("quiz_from")
    quiz_from = (RUNS / qf[1], CACHE / qf[0] / qf[1]) if qf else None
    began = time.time()
    d = delivery.delivery(v["dir"], plan["topic"], store, v["other"], quiz_from, log)
    c = delivery.coverage(v["dir"], v["topic_dir"], store, v["other"])
    gains = test_gains(v)
    for it in c["items"]:
        it.update(gains.get(it["id"], {}))
    qs = {q["id"]: q for q in json.loads((v["topic_dir"] / "quiz.json").read_text())["test"]}
    for it in c["items"]:
        it["question"], it["right"] = qs[it["id"]]["question"], qs[it["id"]]["options"][qs[it["id"]]["answer"]]
    sections = json.loads((v["dir"] / "sections.json").read_text())
    row = {"set": v["set"], "slug": v["slug"], "topic": plan["topic"], "sections": len(sections),
           "planned": len(plan["sections"]), "m9": v["m9"], "mvqs": v["mvqs"], "conflicts": v["conflicts"],
           "delivery": d, "coverage": c, "seconds": round(time.time() - began)}  # fmt: skip
    dl = "--" if d["delivery"] is None else f"{100 * d['delivery']:.0f}"
    log(f"[teach-check] {v['set']}/{v['slug']}: delivery {dl} on {d['questions']} questions, coverage "
        f"{100 * c['coverage']:.0f} ({row['seconds']} s)")  # fmt: skip
    return row


