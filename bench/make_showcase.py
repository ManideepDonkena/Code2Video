"""Showcase of the videos behind every study: one folder per concept with each version of its video, labelled
side-by-side comparisons, and short GIF previews for the README.

    python bench/make_showcase.py            -> demo/showcase/ (videos, not in git), demo/gifs/ (previews, in git),
                                                demo/showcase/index.json (what each file is)

Versions, when they exist:
  local_base        the base video from the local models (qwen3.6 plans, qwen3-coder:30b codes)
  local_autofix     the same, with the model-free timing fixes
  claude_layout     the same, with layout and timing fixed by Claude Opus 5.5 (text unchanged)
  local_F0_learner  the pilot loop's learner repair
  local_F5_learner  the full repair loop (F5), only when the gate kept the revision
  qwen              the local models again, under the generator study's setup (the fair baseline for the Claude models)
  haiku, sonnet, opus   the whole video generated by that Claude model (generator study), best configuration
  qwen_anchor, sonnet_anchor   the same generator with Code2Video's layout (TeachingScene and its 6x6 anchor grid)
"""

from __future__ import annotations

import json
import shutil
import subprocess
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from c2vlab import generate  # noqa: E402

DEMO = ROOT / "demo"
SHOW, GIFS = DEMO / "showcase", DEMO / "gifs"
FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
W, H, BAR = 640, 360, 40


def versions(slug):
    run, gen = ROOT / "runs" / slug, ROOT / "runs" / "claude-gen"
    f5 = {r["topic"]: r for r in json.loads((ROOT / "bench/results/novel12-stages/rows_F5.json").read_text())}
    v = {"local_base": run / "video.mp4", "local_autofix": run / "autofix" / "video.mp4",
         "claude_layout": run / "claude_fixed" / "video.mp4", "local_F0_learner": run / "learner" / "video.mp4"}  # fmt: skip
    if f5.get(slug, {}).get("learner", {}).get("served") == "revision":
        v["local_F5_learner"] = run / "stages" / "F5" / "learner" / "video.mp4"
    for fam in GEN_FAMILIES:
        v[fam.replace("-", "_")] = gen / fam / slug / "video.mp4"
    return {k: p for k, p in v.items() if p.exists()}


GEN_FAMILIES = ("qwen", "haiku", "sonnet", "opus", "qwen-anchor", "sonnet-anchor")
# concepts whose comparisons get a GIF preview (the README and gallery); every concept gets the full video
FEATURED = {"generators": ("tovan-sums", "krell-steps-on-a-grid", "dapple-numbers"),
            "anchor": ("tovan-sums", "krell-steps-on-a-grid", "dapple-numbers")}
LABELS = {"qwen": "Local models (qwen)", "qwen_anchor": "Local models + Code2Video layout",
          "sonnet_anchor": "Sonnet 5.5 + Code2Video layout", "local_base": "Local models (qwen), base", "local_autofix": "Local + timing fixes",
          "claude_layout": "Local + Claude layout fix", "local_F0_learner": "Repair loop F0 (learner)",
          "local_F5_learner": "Repair loop F5 (learner)", "haiku": "Claude Haiku 5.5 generator",
          "sonnet": "Claude Sonnet 5.5 generator", "opus": "Claude Opus 5.5 generator"}  # fmt: skip


def label_png(text, path):
    img = Image.new("RGB", (W, BAR), (24, 32, 40))
    d = ImageDraw.Draw(img)
    d.text((12, 9), text, font=ImageFont.truetype(FONT, 20), fill=(240, 240, 240))
    img.save(path)


def side_by_side(panels, out):
    """panels: [(label, mp4)]; each video scaled to W x H under its label, stacked left to right."""
    args, filt = ["ffmpeg", "-v", "error", "-y"], []
    for i, (label, mp4) in enumerate(panels):
        png = out.with_suffix(f".label{i}.png")
        label_png(label, png)
        args += ["-i", str(mp4), "-loop", "1", "-i", str(png)]
        filt.append(f"[{2 * i}:v]scale={W}:{H}:force_original_aspect_ratio=decrease,pad={W}:{H}:(ow-iw)/2:(oh-ih)/2,"
                    f"fps=15,setsar=1[v{i}];[{2 * i + 1}:v]fps=15[l{i}];[l{i}][v{i}]vstack=shortest=1[p{i}]")  # fmt: skip
    n = len(panels)
    filt.append("".join(f"[p{i}]" for i in range(n)) + (f"hstack=inputs={n}[out]" if n > 1 else "copy[out]"))
    longest = max(float(subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0",
                                        str(m)], capture_output=True, text=True).stdout or 0) for _, m in panels)  # fmt: skip
    args += ["-filter_complex", ";".join(filt), "-map", "[out]", "-t", f"{longest:.2f}", "-c:v", "libx264", "-crf", "30",
             "-preset", "veryfast", "-pix_fmt", "yuv420p", str(out)]  # fmt: skip
    subprocess.run(args, check=True)
    for png in out.parent.glob(out.stem + ".label*.png"):
        png.unlink()


def gif(mp4, out, start, seconds=8, width=960):
    pal = out.with_suffix(".palette.png")
    vf = f"fps=6,scale={width}:-1:flags=lanczos"
    subprocess.run(["ffmpeg", "-v", "error", "-y", "-ss", str(start), "-t", str(seconds), "-i", str(mp4), "-vf",
                    f"{vf},palettegen=max_colors=96", str(pal)], check=True)  # fmt: skip
    subprocess.run(["ffmpeg", "-v", "error", "-y", "-ss", str(start), "-t", str(seconds), "-i", str(mp4), "-i", str(pal),
                    "-lavfi", f"{vf}[x];[x][1:v]paletteuse=dither=bayer", str(out)], check=True)  # fmt: skip
    pal.unlink()


def main():
    topics = json.loads((ROOT / "bench" / "results" / "novel12" / "topics.json").read_text())
    SHOW.mkdir(parents=True, exist_ok=True)
    GIFS.mkdir(parents=True, exist_ok=True)
    index = {"concepts": {}, "comparisons": []}
    for t in topics:
        slug = generate.slug(t)
        vs = versions(slug)
        (SHOW / slug).mkdir(exist_ok=True)
        for k, p in vs.items():
            shutil.copy(p, SHOW / slug / f"{k}.mp4")
        index["concepts"][slug] = {"topic": t, "versions": sorted(vs)}
    comps = []
    for t in topics:  # every concept: the generators side by side
        slug = generate.slug(t)
        vs = versions(slug)
        gens = [k for k in ("qwen", "haiku", "sonnet", "opus") if k in vs]
        if len(gens) > 1:
            comps.append((f"generators_{slug}", t, [(LABELS[k], vs[k]) for k in gens]))
        anch = [k for k in ("qwen", "qwen_anchor", "sonnet", "sonnet_anchor") if k in vs]
        if len(anch) > 1:
            comps.append((f"anchor_{slug}", t, [(LABELS[k], vs[k]) for k in anch]))
    for slug, keys in (("krell-steps-on-a-grid", ("local_base", "local_F5_learner")),
                       ("sorrel-counts-of-lattice-rectangles", ("local_base", "local_F5_learner")),
                       ("dapple-numbers", ("local_base", "claude_layout")),
                       ("krell-steps-on-a-grid", ("local_base", "claude_layout"))):  # fmt: skip
        vs = versions(slug)
        if all(k in vs for k in keys):
            kind = "repair" if "learner" in keys[1] else "layout"
            comps.append((f"{kind}_{slug}", index["concepts"][slug]["topic"], [(LABELS[k], vs[k]) for k in keys]))
    (SHOW / "comparisons").mkdir(exist_ok=True)
    for name, topic, panels in comps:
        out = SHOW / "comparisons" / f"{name}.mp4"
        if not out.exists():
            side_by_side(panels, out)
        kind, slug = name.split("_", 1)
        g = GIFS / f"{name}.gif"
        if kind not in FEATURED or slug in FEATURED[kind]:
            gif(out, g, start=20, width=min(960, 480 * len(panels)))
        elif g.exists():
            g.unlink()
        index["comparisons"].append({"name": name, "topic": topic, "panels": [p[0] for p in panels],
                                     "video": f"showcase/comparisons/{name}.mp4",
                                     "gif": f"gifs/{name}.gif" if g.exists() else None})  # fmt: skip
        print(f"[showcase] {name}: {out.stat().st_size // 1024} KB video" + (f", {g.stat().st_size // 1024} KB gif" if g.exists() else ""))
    (SHOW / "index.json").write_text(json.dumps(index, indent=1, ensure_ascii=False))
    (DEMO / "index.json").write_text(json.dumps(index, indent=1, ensure_ascii=False))
    gallery(index)


def gallery(index):
    """demo/README.md: every comparison, with a GIF preview for the featured concepts, linking to its full video
    (Google Drive when demo/drive_links.json names it, else the local file). Under each: M9 and layout faults per panel."""
    links = json.loads((DEMO / "drive_links.json").read_text()) if (DEMO / "drive_links.json").exists() else {}
    folder = links.get("_folder", "")
    gen = ROOT / "bench" / "results" / "claude-gen"
    m9s = {}
    for fam in GEN_FAMILIES:
        p = gen / f"rows_{fam}.json"
        for r in json.loads(p.read_text()) if p.exists() else []:
            if r.get("teaching"):
                m9s[(fam.replace("-", "_"), r["slug"])] = r["teaching"]["base"]["m9"]
    for r in json.loads((ROOT / "bench/results/novel12-stages/rows_F5.json").read_text()):
        m9s[("local_base", r["topic"])] = r["base"]["m9"]
    faults = {}
    lc = ROOT / "bench" / "results" / "layout-complexity" / "rows.json"
    names = {"local": "local_base", "local_claude_layout": "claude_layout"}
    for r in json.loads(lc.read_text()) if lc.exists() else []:
        k = (names.get(r["version"], r["version"].replace("-", "_")), r["topic"])
        faults[k] = faults.get(k, 0) + r["conflicts"] + r["broken_attachments"]
    key_of = {v: k for k, v in LABELS.items()}
    lines = ["# Demo gallery", "",
             "Every comparison below plays the versions of one video side by side, each under its label. Click a "
             "preview or a link for the full video.",
             f"All videos, every version of every concept: [Google Drive]({folder})." if folder else
             "Full videos are in `demo/showcase/` after `python bench/make_showcase.py`.", "",
             "Under each comparison, per panel: **M9**, what the student learned from 3 frames per section (0 to 100; "
             "higher is better) on the concept's 8-question final quiz, and **faults**, lasting overlaps plus labels "
             "pulled off their shapes, over the video's sections (bench/results/layout-complexity/). One concept at a "
             "time is noisy; the study-level numbers are in [the generator study](../bench/results/claude-gen/report.md).",
             ""]  # fmt: skip
    groups = (("generators", "Local models against Claude models",
               "The whole video is planned and coded by one model family: the local models (qwen3.6 and "
               "qwen3-coder:30b), or Claude Haiku, Sonnet or Opus 5.5. Same concept, same card, same student, same "
               "setup (first-render checks on, our free layout)."),
              ("anchor", "Our free layout against Code2Video's layout",
               "The same generator with our free layout, then with Code2Video's TeachingScene: title on top, lecture "
               "lines fixed on the left, objects placed on a 6x6 grid on the right. Local models first, then Sonnet 5.5."),
              ("repair", "The repair loop (F5)",
               "The base video, then the learner repair that the gate kept: the section the student failed on was edited. "
               "The repair changes what the section teaches, not its layout, and it can add layout faults "
               "(bench/results/repair-layout/)."),
              ("layout", "Layout fix",
               "Our base video, then the same code with layout and timing fixed by Claude Opus 5.5; no text on screen changed."))  # fmt: skip
    for key, title, text in groups:
        comps = [c for c in index["comparisons"] if c["name"].startswith(key + "_")]
        if not comps:
            continue
        lines += [f"## {title}", "", text, ""]
        rest = []
        for c in comps:
            url = links.get(c["name"], c["video"])
            slug = c["name"].split("_", 1)[1]
            parts = []
            for lab in c["panels"]:
                k = key_of[lab]
                bits = ([f"M9 {100 * m9s[(k, slug)]:.0f}"] if (k, slug) in m9s else []) + \
                       ([f"{faults[(k, slug)]} faults"] if (k, slug) in faults else [])
                parts.append(f"{lab}: {', '.join(bits)}" if bits else lab)
            stats = " · ".join(parts)
            if c.get("gif"):
                lines += [f"**{c['topic']}**  \n{stats}", "", f"[![{c['topic']}]({c['gif']})]({url})", ""]
            else:
                rest.append(f"| [{c['topic']}]({url}) | {stats} |")
        if rest:
            lines += ["More concepts (video only):", "", "| Concept | Per panel |", "|---|---|", *rest, ""]
    (DEMO / "README.md").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
